def main():
    rows = list(csv.DictReader(open(r'data\_vdem_fit_all.csv', encoding='utf-8-sig')))
    out = []
    missing = []
    for r in rows:
        code = r['code']
        if code.startswith('OWID_'):
            continue
        if r['status'] == 'flat':
            continue
        if code in ADVANCED:
            continue
        if code not in T_START:
            missing.append((code, r['entity']))
            continue
        try:
            tmid = float(r['ric_tmid'])
        except:
            continue
        t_start, event, region = T_START[code]
        lead = t_start + DELTA - tmid
        out.append((region, code, r['entity'], t_start, event, tmid, lead))

    print('=== 已填 T_start 的国家（%d 个），按提前量排序 ===' % len(out))
    out.sort(key=lambda x: x[6])
    for region, code, ent, ts, ev, tmid, lead in out:
        print('%s|%s|%s|%d|%s|%.2f|%.1f' % (region, code, ent, ts, ev, tmid, lead))

    print()
    print('=== 未填 T_start（待查，%d 个） ===' % len(missing))
    for code, ent in sorted(missing):
        print('%s|%s' % (code, ent))

if __name__ == '__main__':
    main()
